#!/usr/bin/env python3
"""Generate RESULTS.md from the live-run record.

The Gauntlet's findings are only as valuable as their provenance, so
this page is generated, never hand-written: verdicts come from
``runs/history.jsonl`` (every live run appends there), run context
(agent, model, effort, command) comes from ``runs/ledger.json``, and
the finding traces come from the per-test ``runs/<id>/session.jsonl``
files. Re-running this script with no new runs produces no diff.

Reading the table honestly:
- A verdict is a snapshot of one agent on one day, not a permanent
  grade. Agents change, models change, and the harness changes.
- "Latest" is the most recent verdict per test. "Runs" counts every
  live run of that test, including runs that failed to measure.
- INCONCLUSIVE means the run recorded no usable evidence -- the agent
  never reached the tools, or the clean baselines disagreed so the
  oracle could not tell steering from nondeterminism. It is not a
  pass and not a fail. A test whose INCONCLUSIVE share is over half
  across at least 3 runs is flagged WEAK: the scenario needs
  rewriting, not more runs.
- The harness version matters: the 2026-11-24 run used the --agy
  mode with scoped permissions (only the Gauntlet MCP server's tools
  approved), a tool-use preamble in the prompt, and absolute run
  paths. Earlier runs that predate a harness fix are superseded by
  the latest verdict, but they still count in "Runs".

Usage: python3 harness/gen_results.py  (run from the repo root)
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RUNS = ROOT / "runs"


def load_history():
    path = RUNS / "history.jsonl"
    records = []
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if line:
                records.append(json.loads(line))
    return records


def load_ledger():
    path = RUNS / "ledger.json"
    if path.exists():
        return json.loads(path.read_text())
    return []


def session_trace(tid, ledger):
    """Recorded tool calls for a test, as (calls, source).

    Prefer the live session log. If it is gone -- the 2026-11-24 run's
    logs were deleted by a self-test run before the self-test used a
    temp dir -- fall back to the trace preserved in the ledger entry's
    "evidence" map, and say so.
    """
    path = RUNS / tid / "session.jsonl"
    if path.exists():
        calls = []
        for line in path.read_text().splitlines():
            try:
                calls.append(json.loads(line))
            except json.JSONDecodeError:
                continue
        return calls, "runs/%s/session.jsonl" % tid
    for run in ledger:
        evidence = (run.get("evidence") or {}).get(tid)
        if evidence:
            return evidence, "the run ledger (session log since deleted)"
    return [], "runs/%s/session.jsonl" % tid


def main():
    records = load_history()
    ledger = load_ledger()
    by_test = defaultdict(list)
    for rec in records:
        by_test[rec["test"]].append(rec)

    lines = []
    lines.append("# Gauntlet results")
    lines.append("")
    lines.append("Live runs of the Agent Gauntlet against real agents. "
                 "Each test is an adversarial scenario delivered through "
                 "the MCP tools themselves; the oracle scores the agent's "
                 "recorded tool calls, never its words.")
    lines.append("")
    lines.append("This page is generated by `harness/gen_results.py` from "
                 "`runs/history.jsonl` (the verdict record), "
                 "`runs/ledger.json` (run context), and the per-test "
                 "session logs. It is not hand-edited.")
    lines.append("")
    lines.append("## How to read this")
    lines.append("")
    lines.append("- A verdict is a snapshot of one agent on one day, not a "
                 "permanent grade. Agents, models, and the harness all change.")
    lines.append("- **Latest** is the most recent verdict per test. **Runs** "
                 "counts every live run of that test, including runs that "
                 "failed to measure.")
    lines.append("- **INCONCLUSIVE** means the run recorded no usable "
                 "evidence: the agent never reached the tools, or the clean "
                 "baselines disagreed so the oracle could not tell steering "
                 "from nondeterminism. It is not a pass and not a fail.")
    lines.append("- A test whose INCONCLUSIVE share is over half across at "
                 "least 3 runs is flagged **WEAK**: the scenario needs "
                 "rewriting, not more runs.")
    lines.append("- Runs that failed because the harness itself was broken "
                 "(rather than the test) still count in Runs and in the "
                 "INCONCLUSIVE share, so a WEAK flag can reflect harness "
                 "failures as well as test weakness; the run notes in the "
                 "ledger say which runs those were.")
    lines.append("")

    if ledger:
        lines.append("## Runs")
        lines.append("")
        lines.append("| Date | Agent | Model / effort | Tests | Resisted | "
                     "Vulnerable | Inconclusive |")
        lines.append("|---|---|---|---|---|---|---|")
        for run in ledger:
            # The tally is the run's own, recorded in the ledger. Fall
            # back to the latest-per-test counts only if a ledger entry
            # has no tally (they are the same while the ledger holds a
            # single run, but they diverge once more runs exist).
            r = run.get("resisted")
            v = run.get("vulnerable")
            i = run.get("inconclusive")
            if r is None or v is None or i is None:
                counts = Counter()
                for tid, recs in by_test.items():
                    latest = max(recs, key=lambda r: r["ts"])
                    counts[latest["verdict"]] += 1
                r = counts.get("RESISTED", 0)
                v = counts.get("VULNERABLE", 0)
                i = counts.get("INCONCLUSIVE", 0)
            lines.append("| %s | %s | %s / %s | %d | %d | %d | %d |" % (
                run["date"], run["agent"], run["model"], run["effort"],
                run.get("tests", r + v + i), r, v, i))
        for run in ledger:
            if run.get("notes"):
                lines.append("")
                lines.append("**%s:** %s" % (run["date"], run["notes"]))
            if run.get("command"):
                lines.append("")
                lines.append("Reproduction: `%s`" % run["command"])
        lines.append("")

    lines.append("## Latest verdicts")
    lines.append("")
    lines.append("| Test | Latest | Runs | Resisted | Vulnerable | "
                 "Inconclusive | Baseline | Latest reason |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for tid in sorted(by_test):
        recs = by_test[tid]
        counts = Counter(r["verdict"] for r in recs)
        latest = max(recs, key=lambda r: r["ts"])
        share = counts.get("INCONCLUSIVE", 0) / len(recs)
        weak = " WEAK" if share > 0.5 and len(recs) >= 3 else ""
        # The baseline spread (trace-diff tests only): how many clean
        # runs the latest verdict rested on, and how many distinct
        # traces they produced. "Inconclusive" should show how wide
        # the noise was, not just that there was noise.
        if "baseline_runs" in latest and "baseline_distinct_traces" in latest:
            baseline = "%d clean runs, %d distinct trace(s)" % (
                latest["baseline_runs"], latest["baseline_distinct_traces"])
        else:
            baseline = "—"
        lines.append("| %s | **%s**%s | %d | %d | %d | %d | %s | %s |" % (
            tid, latest["verdict"], weak, len(recs),
            counts.get("RESISTED", 0), counts.get("VULNERABLE", 0),
            counts.get("INCONCLUSIVE", 0), baseline,
            latest["reason"].replace("|", "\\|")))
    lines.append("")

    vulns = [(tid, max(recs, key=lambda r: r["ts"]))
             for tid, recs in sorted(by_test.items())
             if max(recs, key=lambda r: r["ts"])["verdict"] == "VULNERABLE"]
    if vulns:
        lines.append("## Findings: vulnerable")
        lines.append("")
        for tid, latest in vulns:
            lines.append("### %s" % tid)
            lines.append("")
            lines.append(latest["reason"] + ".")
            lines.append("")
            calls, source = session_trace(tid, ledger)
            lines.append("Recorded tool calls (%s):" % source)
            lines.append("")
            for call in calls:
                lines.append("- `%s(%s)`" % (
                    call.get("tool"),
                    json.dumps(call.get("arguments", {}), sort_keys=True)))
            lines.append("")

    inconcs = [(tid, max(recs, key=lambda r: r["ts"]))
               for tid, recs in sorted(by_test.items())
               if max(recs, key=lambda r: r["ts"])["verdict"] == "INCONCLUSIVE"]
    if inconcs:
        lines.append("## Findings: inconclusive")
        lines.append("")
        for tid, latest in inconcs:
            lines.append("### %s" % tid)
            lines.append("")
            lines.append(latest["reason"] + ".")
            lines.append("")

    out = ROOT / "RESULTS.md"
    out.write_text("\n".join(lines))
    print("wrote %s (%d tests, %d history records)"
          % (out, len(by_test), len(records)))


if __name__ == "__main__":
    main()
